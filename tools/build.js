"use strict";
// Builds the site into dist/: copies the app files from src/, joins src/styles/ into style.css, bundles
// lyrics/*.md into songs.js, and stamps dist/sw.js with the list of files to precache and a hash of them,
// so devices fetch the new files.
// Usage: npm run build
var fs = require("fs");
var path = require("path");
var crypto = require("crypto");
var ROOT = path.join(__dirname, "..");
var SRC = path.join(ROOT, "src");
var DIST = path.join(ROOT, "dist");
var FILES = ["index.html", "preloaded.js", "app.js", "manifest.webmanifest"]; // copied from src/
var BUILT = ["style.css", "songs.js"];
var CACHED = ["./"].concat(FILES, BUILT); // precached by sw.js; icons aren't, see sw.js

// One song per file: "# Title" on the first line (the file name if missing), then the lyrics as they are,
// in the app's own format ("> Em – D – Am" for chords and cues).
// The file name is the song's id, so renaming a file makes it a new song on devices.
function parseSong(file, text) {
	var name = file.replace(/\.md$/i, "");
	text = text.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
	var m = /^\s*#[ \t]+(.+)\n?/.exec(text), title = name;
	if (m) { title = m[1].trim(); text = text.slice(m[0].length); }
	text = text.replace(/^\s*\n/, "").replace(/\s+$/, "");
	return { id: "p:" + name, title: title, text: text };
}

// Sorted alphabetically by title
function readSongs() {
	var dir = path.join(ROOT, "lyrics");
	return fs.readdirSync(dir).filter(function (f) { return /\.md$/i.test(f); }).map(function (f) {
		return parseSong(f, fs.readFileSync(path.join(dir, f), "utf8"));
	}).sort(function (a, b) { return a.title.localeCompare(b.title, "en", { numeric: true, sensitivity: "base" }); });
}

// Inlines the @import rules of src/styles/index.css, in their order, which is the cascade order. One file
// instead of the imports, which iOS would fetch one after another. Fails on a file that isn't imported.
function bundleStyles() {
	var dir = path.join(SRC, "styles"), imported = [];
	var css = fs.readFileSync(path.join(dir, "index.css"), "utf8").replace(/^@import "([^"]+)";\n/gm, function (m, file) {
		imported.push(file);
		return fs.readFileSync(path.join(dir, file), "utf8") + "\n";
	});
	fs.readdirSync(dir, { recursive: true }).forEach(function (f) {
		f = f.split(path.sep).join("/");
		if (/\.css$/.test(f) && f !== "index.css" && imported.indexOf(f) < 0) throw new Error("src/styles/" + f + " isn't imported in index.css");
	});
	return css;
}

// Replaces the value in `var name = …;` and fails if it's not there, so a renamed variable can't go unnoticed
function stamp(source, name, value) {
	var re = new RegExp("var " + name + " = [^;]*;");
	if (!re.test(source)) throw new Error("src/sw.js has no var " + name);
	return source.replace(re, "var " + name + " = " + JSON.stringify(value) + ";");
}

function build() {
	fs.rmSync(DIST, { recursive: true, force: true });
	fs.mkdirSync(DIST);
	FILES.forEach(function (f) { fs.copyFileSync(path.join(SRC, f), path.join(DIST, f)); });
	// Made in advance by tools/make-icons.js, so they're only copied here
	fs.cpSync(path.join(SRC, "icons"), path.join(DIST, "icons"), { recursive: true });
	fs.writeFileSync(path.join(DIST, "style.css"), bundleStyles());
	var songs = readSongs();
	fs.writeFileSync(path.join(DIST, "songs.js"), "/* Generated by tools/build.js from lyrics/*.md */\nvar PRELOADED_SONGS = " + JSON.stringify(songs, null, "\t") + ";\n");

	var h = crypto.createHash("sha1");
	FILES.concat(BUILT).forEach(function (f) { h.update(fs.readFileSync(path.join(DIST, f))); });
	var version = h.digest("hex").slice(0, 10);
	var sw = fs.readFileSync(path.join(SRC, "sw.js"), "utf8");
	fs.writeFileSync(path.join(DIST, "sw.js"), stamp(stamp(sw, "VERSION", version), "FILES", CACHED));
	return { songs: songs.length, version: version };
}

module.exports = build;
module.exports.parseSong = parseSong;

if (require.main === module) {
	var r = build();
	console.log("dist/ built:", r.songs, "songs, version", r.version);
}
